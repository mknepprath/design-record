package main

import (
	"fmt"
	"slices"
	"sort"
	"strings"
)

// renderIndex builds INDEX.md: every project with the documents that back
// it, then every document grouped by layer and kind.
func renderIndex(docs []doc) (string, error) {
	var b strings.Builder
	// The permalink makes INDEX.md the home page of the Pages site.
	b.WriteString("---\ntitle: Index\npermalink: /\n---\n\n")
	b.WriteString("# Index\n\nGenerated by `make index`. Do not edit by hand. About this record: [README](README.md).\n\n")

	var projects []doc
	for _, d := range docs {
		if d.Kind.Name == "project" {
			projects = append(projects, d)
		}
	}
	sort.Slice(projects, func(i, j int) bool { return projects[i].Title() < projects[j].Title() })

	fmt.Fprintf(&b, "## Projects (%d)\n\n", len(projects))
	b.WriteString("| Project | Status | Owner | Date |\n| --- | --- | --- | --- |\n")
	for _, p := range projects {
		fmt.Fprintf(&b, "| [%s](%s) | %s | %s | %s |\n", esc(p.Title()), p.Path, p.Status(), esc(p.Fields["owner"]), p.Date())
	}
	b.WriteString("\n")

	for _, p := range projects {
		var backing []doc
		for _, d := range docs {
			if slices.Contains(d.Projects(), p.Slug()) {
				backing = append(backing, d)
			}
		}
		fmt.Fprintf(&b, "### %s\n\n", esc(p.Title()))
		if len(backing) == 0 {
			b.WriteString("No documents yet.\n\n")
			continue
		}
		for _, l := range []layer{layerDecision, layerSynthesis, layerEvidence} {
			for _, d := range backing {
				if d.Kind.Layer == l {
					fmt.Fprintf(&b, "- %s: %s\n", kindLabel(d), link(d))
				}
			}
		}
		b.WriteString("\n")
	}

	sections := []struct {
		heading string
		layer   layer
	}{
		{"Decisions and specs", layerDecision},
		{"Synthesis", layerSynthesis},
		{"Evidence", layerEvidence},
	}
	for _, s := range sections {
		fmt.Fprintf(&b, "## %s\n\n", s.heading)
		any := false
		for _, k := range kinds {
			if k.Layer != s.layer {
				continue
			}
			var group []doc
			for _, d := range docs {
				if d.Kind.Name == k.Name {
					group = append(group, d)
				}
			}
			if len(group) == 0 {
				continue
			}
			any = true
			sortGroup(group)
			fmt.Fprintf(&b, "### %s (%d)\n\n", plural(k.Name), len(group))
			if k.Numbered {
				b.WriteString("| Ref | Title | Status | Date |\n| --- | --- | --- | --- |\n")
				for _, d := range group {
					fmt.Fprintf(&b, "| %s | [%s](%s) | %s | %s |\n", d.Ref(), esc(d.Title()), d.Path, d.Status(), d.Date())
				}
			} else {
				b.WriteString("| Title | Date |\n| --- | --- |\n")
				for _, d := range group {
					fmt.Fprintf(&b, "| [%s](%s) | %s |\n", esc(d.Title()), d.Path, d.Date())
				}
			}
			b.WriteString("\n")
		}
		if !any {
			b.WriteString("None yet.\n\n")
		}
	}
	return strings.TrimRight(b.String(), "\n") + "\n", nil
}

func sortGroup(group []doc) {
	sort.Slice(group, func(i, j int) bool {
		a, c := group[i], group[j]
		if a.Kind.Numbered {
			return a.Number() < c.Number()
		}
		if a.Kind.Dated && a.Date() != c.Date() {
			return a.Date() > c.Date() // newest first
		}
		return a.Title() < c.Title()
	})
}

func kindLabel(d doc) string {
	if d.Kind.Numbered {
		return d.Ref()
	}
	return strings.ToUpper(d.Kind.Name[:1]) + d.Kind.Name[1:]
}

func link(d doc) string {
	return fmt.Sprintf("[%s](%s)", esc(d.Title()), d.Path)
}

func plural(name string) string {
	switch name {
	case "adr":
		return "ADRs"
	case "spec":
		return "Specs"
	case "study":
		return "Studies"
	case "feedback", "glossary":
		return strings.ToUpper(name[:1]) + name[1:]
	}
	return strings.ToUpper(name[:1]) + name[1:] + "s"
}

func esc(s string) string { return strings.ReplaceAll(s, "|", `\|`) }
